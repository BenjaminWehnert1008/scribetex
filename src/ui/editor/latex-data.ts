/**
 * Words the editor offers while typing. The lists are written for this app:
 * the commands and environments that come up in everyday papers, reports and
 * slides. `${}` marks where the cursor goes; `${name}` is a placeholder.
 */
export interface CommandSpec {
  /** Without the backslash. */
  name: string;
  /** Text inserted after the backslash, as a snippet. Defaults to the name. */
  snippet?: string;
  detail?: string;
}

const arg = (name: string, detail?: string): CommandSpec => ({ name, snippet: `${name}{\${}}`, detail });
const plain = (name: string, detail?: string): CommandSpec => ({ name, detail });

